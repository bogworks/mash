// killAfterIssue makes enroll.AfterIssueHook panic, which stands for a kill between the user being signed and the
// directory record being written. The hook is restored when the test ends.
func killAfterIssue(t *testing.T) {
	t.Helper()
	prev := enroll.AfterIssueHook
	enroll.AfterIssueHook = func() { panic("killed after the issue record") }
	t.Cleanup(func() { enroll.AfterIssueHook = prev })
}

// runKilled runs the command in process with the kill in place and reports whether the run was killed, and what it
// printed before that (nothing, when it was killed: the output is only returned by a run that finished).
func runKilled(t *testing.T, h *fleetEnv, args ...string) (killed bool) {
	t.Helper()
	prev := enroll.AfterIssueHook
	killAfterIssue(t)
	defer func() {
		enroll.AfterIssueHook = prev
		if recover() != nil {
			killed = true
		}
	}()
	h.run(args...)
	return false
}

// issuedKeysFor is the public keys the issued bucket holds for the address.
func issuedKeysFor(t *testing.T, h *fleetEnv, a sap.Address) []string {
	t.Helper()
	recs, err := issuedRecords(t, h.adminOf())
	if err != nil {
		t.Fatal(err)
	}
	var keys []string
	for _, r := range recs {
		if r.Address == a.Flat() {
			keys = append(keys, r.PublicKey)
		}
	}
	return keys
}

// recordUsersFor is the users of the directory records at the address.
func recordUsersFor(h *fleetEnv, a sap.Address) []string {
	var users []string
	for _, r := range h.records() {
		if strings.HasPrefix(r, a.String()+"//") {
			users = append(users, strings.TrimPrefix(r, a.String()+"//"))
		}
	}
	return users
}

// seedFilePub is the public key of the bare seed in a staged seed file.
func seedFilePub(t *testing.T, path string) string {
	t.Helper()
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	kp, err := nkeys.FromSeed([]byte(strings.TrimSpace(string(raw))))
	if err != nil {
		t.Fatal(err)
	}
	pub, _ := kp.PublicKey()
	return pub
}

// AT-004, NFR-001: a create killed between the user being signed and the record being written, run again, completes
// with one identity.
func TestEndpointKilledCreateRerunCompletesWithOneIdentity(t *testing.T) {
	for _, makeKey := range []bool{false, true} {
		name := "public key and jwt out"
		if makeKey {
			name = "make key, staged seed"
		}
		t.Run(name, func(t *testing.T) {
			h := newFleetEnv(t)
			fakeRevoke(t, nil)
			fakeKeyRevoked(t, func(string) (bool, error) { return false, nil })
			a := ad("killed")
			dir := t.TempDir()

			var args []string
			var outFile, pub string
			if makeKey {
				outFile = h.creds(a)
				args = []string{"endpoint", "create", a.String(), "--make-key"}
			} else {
				var keyFile string
				pub, keyFile, _ = epKey(t, dir, "k")
				outFile = filepath.Join(dir, "k.jwt")
				args = []string{"endpoint", "create", a.String(), "--public-key", keyFile, "--jwt-out", outFile}
			}

			if !runKilled(t, h, args...) {
				t.Fatal("the hook did not kill the run")
			}

			// after the kill: signed and recorded as issued, but no directory record and no output file
			keys := issuedKeysFor(t, h, a)
			if len(keys) != 1 {
				t.Fatalf("issued keys after the kill: %v", keys)
			}
			if makeKey {
				// the key is generated by the run; it is known from the staged seed that waits for the rerun
				if gone(t, outFile+".pending") {
					t.Fatal("no staged seed after the kill")
				}
				pub = seedFilePub(t, outFile+".pending")
			}
			if keys[0] != pub {
				t.Fatalf("issued key %s, want %s", keys[0], pub)
			}
			if rec, found, err := h.adminOf().IssuedByKey(context.Background(), pub); err != nil || !found || rec.Address != a.Flat() {
				t.Fatalf("issue record for the key: %+v found=%v err=%v", rec, found, err)
			}
			if r, found := h.record(a); found {
				t.Fatalf("directory record after the kill: %+v", r)
			}
			if !gone(t, outFile) {
				t.Errorf("%s exists after the kill", outFile)
			}

			// the same command, run again, then once more
			for _, label := range []string{"rerun", "third run"} {
				so, se, code := h.run(args...)
				// Observed: the third run exits 1, refused (file_exists): the output file is never overwritten. It changes nothing.
				if code != 0 {
					if label == "rerun" {
						t.Fatalf("rerun exit %d: %q %q", code, so, se)
					}
					t.Logf("third run refused: exit %d %q %q", code, so, se)
				}
				if got := issuedKeysFor(t, h, a); len(got) != 1 || got[0] != pub {
					t.Errorf("%s: issued keys %v, want only %s", label, got, pub)
				}
				if users := recordUsersFor(h, a); len(users) != 1 || users[0] != pub {
					t.Errorf("%s: directory users %v, want only %s", label, users, pub)
				}
				if !gone(t, outFile+".pending") {
					t.Errorf("%s: pending file left", label)
				}
				noSecrets(t, so, se)
				if label != "rerun" {
					t.Logf("third run: exit %d stdout %q", code, so)
					continue
				}
				if m := fileMode(t, outFile); m != 0o600 {
					t.Errorf("%s mode %o, want 600", outFile, m)
				}
				var sub string
				if makeKey {
					sub = credsSeedPub(t, outFile)
				} else {
					raw, err := os.ReadFile(outFile)
					if err != nil {
						t.Fatal(err)
					}
					uc, err := jwt.DecodeUserClaims(strings.TrimSpace(string(raw)))
					if err != nil {
						t.Fatal(err)
					}
					sub = uc.Subject
				}
				if sub != pub {
					t.Errorf("the file names key %s, the directory record %s", sub, pub)
				}
			}
		})
	}
}

// credsSeedPub is the public key of the seed in a creds file.
func credsSeedPub(t *testing.T, path string) string {
	t.Helper()
	kp, err := nkeys.FromSeed(credsSeed(t, path))
	if err != nil {
		t.Fatal(err)
	}
	pub, _ := kp.PublicKey()
	return pub
}

// A killed run with --json prints no document, so there is nothing for the rerun's document to contradict.
func TestEndpointKilledCreateJSONPrintsNothing(t *testing.T) {
	h := newFleetEnv(t)
	fakeRevoke(t, nil)
	a := ad("killedjson")
	dir := t.TempDir()
	_, keyFile, _ := epKey(t, dir, "k")
	args := []string{"endpoint", "create", a.String(), "--public-key", keyFile, "--jwt-out", filepath.Join(dir, "k.jwt"), "--json"}

	// a panic unwinds before h.run returns, so a killed run has no output to return
	if !runKilled(t, h, args...) {
		t.Fatal("the hook did not kill the run")
	}
	so, se, code := h.run(args...)
	if code != 0 || epDocOf(t, so).Outcome != "created" {
		t.Fatalf("rerun: %d %q %q", code, so, se)
	}
	noSecrets(t, so, se)
}
